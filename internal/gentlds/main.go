// Command gentlds writes tlds.go from the IANA list of top-level domains.
//
// Run it through go generate from the module root:
//
//	go generate ./...
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strings"
)

const ianaURL = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt"

// reserved are names that are not in the root zone but that people use as
// TLDs in examples, labs and internal networks (RFC 2606, RFC 6761,
// RFC 7686, RFC 6762 and the ICANN-reserved "internal").
var reserved = []string{"example", "internal", "invalid", "local", "localhost", "onion", "test"}

func main() {
	out := flag.String("o", "tlds.go", "output file")
	src := flag.String("src", ianaURL, "IANA TLD list (URL or file)")
	flag.Parse()

	data, err := read(*src)
	if err != nil {
		log.Fatal(err)
	}

	var version string
	seen := map[string]bool{}
	var names []string
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "#") {
			if version == "" {
				version = strings.TrimSpace(strings.TrimPrefix(line, "#"))
			}
			continue
		}
		name := strings.ToLower(line)
		if !seen[name] {
			seen[name] = true
			names = append(names, name)
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if len(names) < 1000 {
		log.Fatalf("IANA list has only %d names; refusing to write", len(names))
	}
	for _, r := range reserved {
		if !seen[r] {
			seen[r] = true
			names = append(names, r)
		}
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by internal/gentlds; DO NOT EDIT.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package safeioc")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "// tlds holds the lower-case top-level domains of the IANA root zone\n")
	fmt.Fprintf(&b, "// (%s)\n", version)
	fmt.Fprintf(&b, "// plus the reserved names %s, sorted.\n", strings.Join(reserved, ", "))
	fmt.Fprintln(&b, "var tlds = [...]string{")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	fmt.Fprintln(&b, "}")

	src2, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src2, 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(src string) ([]byte, error) {
	if !strings.HasPrefix(src, "https://") {
		return os.ReadFile(src)
	}
	resp, err := http.Get(src)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", src, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
